window.HELP.es = `
<h3>Crear una imagen</h3>
<p>Elige un origen (archivos FLAC/WAV, una pista por archivo, o un archivo .cue), completa la información —con MusicBrainz si quieres—, indica el número de disco y el número total de discos y elige dónde guardar. El audio se comprime en FLAC nivel 8 y se verifica durante la codificación; después se relee y se comprueba toda la imagen.</p>
<h3>Álbumes de varios discos</h3>
<p>Una imagen corresponde a un disco físico. Para el disco 2, usa «Asociar a un disco existente» y elige la imagen del disco 1: el álbum comparte entonces el mismo identificador y FISO Explorer agrupa los discos que encuentra en la misma carpeta.</p>
<h3>Los tres estados de integridad</h3>
<p><b>Archivo válido</b>: la estructura es conforme. <b>Audio íntegro</b>: el audio decodificado coincide exactamente con las huellas guardadas. <b>Extracción verificada</b>: el contenido se ha comparado con una referencia externa. Estos estados son independientes.</p>
<h3>Pre-gaps</h3>
<p>El pre-gap (INDEX 00) de una pista se guarda al final de la pista anterior, como en la cronología del disco. Las transiciones siguen sin cortes y cada pista se extrae en FLAC sin recodificar.</p>
<h3>Extraer un CD de audio</h3>
<p>En «Crear», elige «CD de audio». FISO Explorer lee la tabla de contenido, el CD-Text y los códigos ISRC y MCN, y consulta MusicBrainz. El modo seguro relee cada sector hasta obtener dos lecturas idénticas; los sectores que siguen siendo dudosos se indican en el informe, nunca se ocultan. Indica el desfase de lectura de tu unidad (botón «Buscar en AccurateRip») para que la verificación AccurateRip sea posible.</p>
<h3>Grabar un CD</h3>
<p>Una imagen FISO es un archivo de conservación: guarda el audio exactamente como se creó, incluida la alta resolución. Para grabar un CD, usa «Convertir en imagen de CD de audio grabable»: FISO Explorer crea una imagen BIN/CUE en formato CD de audio (pistas colocadas en los sectores del CD, conversión solo si la aceptas), que luego grabas con tu programa de grabación habitual en modo Disc-at-Once (DAO). Los títulos, pre-gaps, índices, ISRC y MCN se incluyen en el archivo CUE; la imagen FISO nunca se modifica.</p>
<h3>Iconos en el Finder</h3>
<p>FISO Explorer instala una extensión Quick Look: los archivos .fiso muestran la portada de su álbum. Si los iconos no aparecen, haz clic en «Reactivar los iconos» en los Ajustes y vuelve a abrir la ventana del Finder. Si la aplicación se descargó, macOS puede bloquear su extensión mientras siga marcada como «descargada»: en el Terminal, ejecuta <code>xattr -dr com.apple.quarantine "/Applications/FISO Explorer.app"</code>, vuelve a abrir FISO Explorer y reactiva los iconos.</p>`;
